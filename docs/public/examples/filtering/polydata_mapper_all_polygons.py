grid_0.InsertNextCell(a_triangle_strip.GetCellType(), a_triangle_strip.GetPointIds())
grid_0.SetPoints(triangle_strip_points)
geometry_0 = vtkGeometryFilter()
geometry_0.SetInputData(grid_0)
tri_filter_0 = vtkTriangleFilter()
tri_filter_0.SetInputConnection(geometry_0.GetOutputPort())
mapper_0 = vtkPolyDataMapper()
mapper_0.SetInputConnection(geometry_0.GetOutputPort())
mapper_0.SetLookupTable(lut)
mapper_0.SetScalarRange(0, 4)
actor_0 = vtkActor()
actor_0.SetMapper(mapper_0)
actor_0.AddPosition(0, 0, 0)

