triangle_strip_cell_normals.SetNumberOfTuples(1)
triangle_strip_cell_normals.InsertTuple3(0, 0, 0, 1)

# Triangle strip cell
a_triangle_strip = vtkTriangleStrip()
a_triangle_strip.GetPointIds().SetNumberOfIds(5)
a_triangle_strip.GetPointIds().SetId(0, 0)
a_triangle_strip.GetPointIds().SetId(1, 1)
a_triangle_strip.GetPointIds().SetId(2, 2)
a_triangle_strip.GetPointIds().SetId(3, 3)
a_triangle_strip.GetPointIds().SetId(4, 4)

# Lookup table
lut = vtkLookupTable()
lut.SetNumberOfColors(5)
lut.SetTableValue(0, 0, 0, 1, 1)
lut.SetTableValue(1, 0, 1, 0, 1)
lut.SetTableValue(2, 0, 1, 1, 1)
lut.SetTableValue(3, 1, 0, 0, 1)
lut.SetTableValue(4, 1, 0, 1, 1)

