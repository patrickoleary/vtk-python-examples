triangle_strip_point_scalars.InsertValue(2, 0)
triangle_strip_point_scalars.InsertValue(3, 0)
triangle_strip_point_scalars.InsertValue(4, 0)

# Cell scalars
triangle_strip_cell_scalars = vtkFloatArray()
triangle_strip_cell_scalars.SetNumberOfTuples(1)
triangle_strip_cell_scalars.InsertValue(0, 1)

# Point normals
triangle_strip_point_normals = vtkFloatArray()
triangle_strip_point_normals.SetNumberOfComponents(3)
triangle_strip_point_normals.SetNumberOfTuples(5)
triangle_strip_point_normals.InsertTuple3(0, 0, 0, 1)
triangle_strip_point_normals.InsertTuple3(1, 0, 1, 0)
triangle_strip_point_normals.InsertTuple3(2, 0, 1, 1)
triangle_strip_point_normals.InsertTuple3(3, 1, 0, 0)
triangle_strip_point_normals.InsertTuple3(4, 1, 0, 1)

# Cell normals
triangle_strip_cell_normals = vtkFloatArray()
